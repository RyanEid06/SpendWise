import { expect, test } from '@playwright/test';
import { BACKUP_PASSPHRASE, mockReadyAuthenticatedBackend, openSettings, startFresh } from './helpers';

test('blank-description draft survives AI failure/retry and restart, then History/search/statistics/backup retain one expense', async ({ page }) => {
  await mockReadyAuthenticatedBackend(page);
  await startFresh(page);
  let requests = 0;
  await page.route('**/api/gemini/smart-capture', route => {
    requests++;
    return route.fulfill({ status: 503, headers: { 'X-Backend-Version': 'abc123def456' }, json: { error: 'AI_TEMPORARILY_UNAVAILABLE' } });
  });
  await page.getByRole('button', { name: 'Add Expense', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Add Expense' });
  await editor.getByRole('spinbutton').fill('20');
  await editor.getByRole('button', { name: 'Transportation', exact: true }).click();
  await editor.getByTestId('tool-smart-button').click();
  const chooser = page.waitForEvent('filechooser');
  await editor.getByRole('button', { name: 'Choose Photo', exact: true }).click();
  await (await chooser).setFiles('tests/fixtures/media/wp32-photo-01.jpg');
  await editor.getByRole('button', { name: 'Analyze with Gemini', exact: true }).click();
  await expect(editor.getByRole('spinbutton')).toHaveValue('20');
  await editor.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect.poll(() => requests).toBe(2);
  await expect(editor.getByRole('button', { name: 'Retry', exact: true })).toBeVisible();
  const diagnostics = await page.evaluate(() => JSON.parse(localStorage.getItem('spendwise_technical_diagnostics_v1') || '{}'));
  expect(diagnostics.recentErrors).toEqual(expect.arrayContaining([expect.objectContaining({ operation: 'api.request',
    code: 'temporary_unavailable', backendVersion: 'abc123def456', feature: 'smart-capture', stage: 'ai_dispatch', requestId: expect.stringMatching(/^[a-f0-9-]{36}$/) })]));
  await expect(editor.getByRole('textbox', { name: /Description/ })).toHaveValue('');
  await expect(editor.getByTestId('draft-status')).toHaveText('Unfinished expense protected');
  await page.reload();
  await expect(editor.getByRole('spinbutton')).toHaveValue('20');
  await expect(editor.getByRole('textbox', { name: /Description/ })).toHaveValue('');
  await editor.getByRole('button', { name: 'Save Expense', exact: true }).click();
  await expect(editor).toBeHidden();
  const ledger = () => page.evaluate(() => JSON.parse(localStorage.getItem('spendwise_expenses') || '[]'));
  expect(await ledger()).toHaveLength(1);
  expect((await ledger())[0]).toMatchObject({ amount: 20, description: 'Transportation', category: 'Transportation' });
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('searchbox').fill('Transportation');
  await expect(page.getByRole('button', { name: /^Transportation,/ })).toBeVisible();
  await page.getByRole('button', { name: 'Statistics', exact: true }).click();
  await expect(page.getByText('Transportation', { exact: true }).filter({ visible: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await expect(page.getByRole('searchbox')).toHaveValue('Transportation');
  await openSettings(page);
  await page.getByText('Backup & Restore', { exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByText('Create encrypted backup', { exact: true }).click();
  let modal = page.getByRole('dialog');
  await modal.locator('input[type=password]').nth(0).fill(BACKUP_PASSPHRASE);
  await modal.locator('input[type=password]').nth(1).fill(BACKUP_PASSPHRASE);
  await modal.getByRole('button', { name: 'Create encrypted backup' }).click();
  const backupPath = await (await download).path();
  await page.locator('input[accept=".swb3,.zip,application/octet-stream,application/zip"]').setInputFiles(backupPath!);
  modal = page.getByRole('dialog');
  await modal.locator('input[type=password]').fill(BACKUP_PASSPHRASE);
  await modal.getByRole('button', { name: 'Unlock backup' }).click();
  const preview = page.getByRole('dialog', { name: 'Backup restore', exact: true });
  await preview.getByRole('button', { name: 'Replace', exact: true }).first().click();
  await preview.getByRole('button', { name: 'Replace', exact: true }).last().click();
  await expect(preview).toBeHidden();
  expect(await ledger()).toHaveLength(1);
  expect((await ledger())[0].description).toBe('Transportation');
});
