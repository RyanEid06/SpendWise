export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function t(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = (dictionary as any)[key] || (TRANSLATIONS.en as any)[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function getLocalizedMonthName(my: MonthYear, lang: Language): string {
  const date = new Date(my.year, my.month - 1, 1);
  const locale = lang === 'ar' ? 'ar-EG' : lang === 'fr' ? 'fr-FR' : 'en-US';
  return date.toLocaleDateString(locale, { month: 'long', year: 'numeric' });
}

export function getLocalizedCategoryName(categoryName: string, lang: Language): string {
  const mapping: Record<string, TranslationKey> = {
    food: 'catFood',
    groceries: 'catGroceries',
    transportation: 'catTransportation',
    shopping: 'catShopping',
    entertainment: 'catEntertainment',
    bills: 'catBills',
    subscriptions: 'catSubscriptions',
    health: 'catHealth',
    education: 'catEducation',
    electronics: 'catElectronics',
    travel: 'catTravel',
    other: 'catOther',
  };
  const key = mapping[categoryName.toLowerCase()];
  return key ? t(lang, key) : categoryName;
}
